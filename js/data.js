const Store = {
  key: 'permtransport.state.v9',
  state: null,

  load() {
    try {
      const raw = localStorage.getItem(this.key);
      if (raw) {
        this.state = JSON.parse(raw);
        if (!this.state.theme) this.state.theme = 'system';
        this.normalize();
        if (!this.state.digitalCards) {
          this.state.digitalCards = JSON.parse(JSON.stringify(DEFAULT_DIGITAL_CARDS));
          this.state.activeDigital = 0;
          this.save();
        }
        return this.state;
      }
    } catch (e) { /* приватный режим — работаем в памяти */ }
    this.state = {
      cards: JSON.parse(JSON.stringify(DEFAULT_CARDS)),
      activeCard: 0,
      orders: JSON.parse(JSON.stringify(DEFAULT_ORDERS)),
      currentOrder: null,
      favorites: [],
      digitalCards: JSON.parse(JSON.stringify(DEFAULT_DIGITAL_CARDS)),
      activeDigital: 0,
      theme: 'system',
      lastPayMethod: 'sber'
    };
    this.save();
    return this.state;
  },
  /* защита от повреждённого состояния: индексы карт всегда в границах */
  normalize() {
    const st = this.state;
    if (!Array.isArray(st.cards) || !st.cards.length)
      st.cards = JSON.parse(JSON.stringify(DEFAULT_CARDS));
    if (!Array.isArray(st.digitalCards) || !st.digitalCards.length)
      st.digitalCards = JSON.parse(JSON.stringify(DEFAULT_DIGITAL_CARDS));
    st.activeCard = Math.min(Math.max(0, st.activeCard | 0), st.cards.length - 1);
    st.activeDigital = Math.min(Math.max(0, st.activeDigital | 0), st.digitalCards.length - 1);
  },
  save() {
    try { localStorage.setItem(this.key, JSON.stringify(this.state)); } catch (e) {}
  },
  reset() {
    try { localStorage.removeItem(this.key); } catch (e) {}
    this.state = null;
    this.load();
  },
  get cards()   { return this.state.cards; },
  get digitalCards() { return this.state.digitalCards; },
  get digital() { return this.state.digitalCards[this.state.activeDigital]; },
  get card()    { return this.state.cards[this.state.activeCard]; },
  get orders()  { return this.state.orders; }
};

