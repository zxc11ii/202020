/* Дата в формате ДД.ММ.ГГГГ и та же дата через год */
function fmtRuDate(iso) {
  const d = new Date(iso);
  return pad2(d.getDate()) + '.' + pad2(d.getMonth() + 1) + '.' + d.getFullYear();
}
function plusYear(iso) {
  const d = new Date(iso);
  d.setFullYear(d.getFullYear() + 1);
  return pad2(d.getDate()) + '.' + pad2(d.getMonth() + 1) + '.' + d.getFullYear();
}

/* Расписание прибытий для остановки — псевдослучайно, но стабильно по id */
function arrivalsFor(stopId) {
  let seed = 0;
  for (let i = 0; i < stopId.length; i++) seed += stopId.charCodeAt(i) * (i + 7);
  const out = [];
  const count = 4 + (seed % 3);
  for (let i = 0; i < count; i++) {
    const r = ROUTES[(seed + i * 5) % ROUTES.length];
    out.push({
      route: r.num,
      type: r.type,
      title: r.title,
      minutes: ((seed + i * 13) % 18) + 1
    });
  }
  return out.sort((a, b) => a.minutes - b.minutes);
}
